import type { AnnualPlan } from './data/regions';
import type { Zone } from './lib/zones';

/** Shared data model for the four wizard steps. */

export type VesselId = string;

export type VesselCategory = 'Passenger' | 'Offshore' | 'Special';

/** Key information for one specific vessel. Any field may be omitted. */
export interface VesselSpecs {
  /** Length overall, m. */
  loa?: number;
  /** Beam, m. */
  beam?: number;
  /** Passengers or special personnel (technicians, scientists), persons. */
  passengers?: number;
  /** Crew, persons. */
  crew?: number;
  /** Air-conditioned floor area, m². */
  conditionedArea?: number;
  /** Gross tonnage, GT. */
  grossTonnage?: number;
}

export interface Vessel {
  id: VesselId;
  name: string;
  category: VesselCategory;
  /** One-line HVAC characteristic shown on the card and in the library list. */
  tagline: string;
  specs: VesselSpecs;
  /** Shown as a card at the top of step 1 rather than only in the library. */
  featured?: boolean;
  /** Longer text shown once the vessel is selected. */
  description?: string;
  /** Key into the figure registry in `components/figures/VesselFigure.tsx`. */
  figure?: string;
}

/** One sample of the weather profile: conditions at a position and time. */
export interface WeatherPoint {
  /** ISO timestamp of the sample. */
  time: string;
  /** Representative vessel position at that time. */
  lat: number;
  lon: number;
  /** Ambient dry-bulb air temperature, °C. */
  airTemp: number;
  /** Seawater temperature, °C. */
  seawaterTemp: number;
  /** Relative humidity, %. */
  relativeHumidity: number;
  /** Global solar irradiance on a horizontal surface, W/m². */
  solarRadiation: number;
}

/**
 * One measured year for a region: a value per hour, 8760 of them, starting
 * 1 January 00:00 GMT. Generated by `scripts/import-weather.mjs`.
 */
export interface HourlyYear {
  /** Where and when the data is from, shown in step 2. */
  source: string;
  /** Dry-bulb air temperature, °C. */
  airTemp: number[];
  /** Seawater temperature, °C. */
  seawaterTemp: number[];
  /** Relative humidity, %. */
  relativeHumidity: number[];
  /** Mean of the irradiance on the four vertical orientations, W/m². */
  solarRadiation: number[];
}

/** Step 2 — where the vessel operates through the year. */
export interface WeatherCondition {
  /** Main operating region for each month, January first. */
  plan: AnnualPlan;
}

/** Step 3 — every value is kept as a string so partially typed input survives. */
export type DesignParameters = Record<string, string>;

export type SystemLayoutId =
  | 'chiller-2way'
  | 'chiller-3way'
  | 'chiller-2way-fc'
  | 'chiller-3way-fc'
  | 'tems';

/** Air-side distribution topology chosen in step 4. */
export type AirSystemId =
  | 'ahu'
  | 'ahu-wheel'
  | 'ahu-fcu'
  | 'ahu-wheel-fcu';

/** Step 4 */
export interface AirWaterSystem {
  layout: SystemLayoutId | null;
  /** Air-side distribution; null until one is picked. */
  airSystem: AirSystemId | null;
  parameters: Record<string, string>;
}

export interface ProjectData {
  projectName: string;
  vesselId: VesselId | null;
  /** Step 1 — room groups; their totals feed the heat balance. */
  zones: Zone[];
  weather: WeatherCondition;
  design: DesignParameters;
  system: AirWaterSystem;
}
