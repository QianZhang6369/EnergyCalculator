/**
 * Turns an hourly weather export into a data module for a region.
 *
 *   node scripts/import-weather.mjs <file.csv> <exportName> <source label>
 *
 * The CSV needs the columns time, solar_mean_Wm2, seawater_C, temp_C and
 * rh_pct, one row per hour of a non-leap year in GMT (8760 rows). Only those
 * four measures are kept. The module is written to src/data/weather/.
 */
import { readFileSync, writeFileSync } from 'node:fs';

const [file, exportName, source] = process.argv.slice(2);
if (!file || !exportName || !source) {
  console.error('usage: node scripts/import-weather.mjs <file.csv> <exportName> <source label>');
  process.exit(1);
}

const lines = readFileSync(file, 'utf8').replace(/^\uFEFF/, '').trim().split(/\r?\n/);
const header = lines[0].split(',');
const column = (name) => {
  const i = header.indexOf(name);
  if (i < 0) throw new Error(`Missing column ${name}`);
  return i;
};
const cols = {
  airTemp: column('temp_C'),
  seawaterTemp: column('seawater_C'),
  relativeHumidity: column('rh_pct'),
  solarRadiation: column('solar_mean_Wm2'),
};

const rows = lines.slice(1).map((line) => line.split(','));
if (rows.length !== 8760) throw new Error(`Expected 8760 hourly rows, found ${rows.length}`);

const series = Object.fromEntries(
  Object.entries(cols).map(([key, i]) => [
    key,
    rows.map((row, n) => {
      const v = Number(row[i]);
      if (row[i] === '' || Number.isNaN(v)) throw new Error(`Bad ${key} in row ${n + 2}`);
      return v;
    }),
  ]),
);

const out = `import type { HourlyYear } from '../../types';

// Generated by scripts/import-weather.mjs — do not edit by hand.
export const ${exportName}: HourlyYear = {
  source: ${JSON.stringify(source)},
${Object.entries(series)
  .map(([key, values]) => `  ${key}: [${values.join(',')}],`)
  .join('\n')}
};
`;
const target = new URL(`../src/data/weather/${exportName}.ts`, import.meta.url);
writeFileSync(target, out);
console.log(`Wrote ${exportName}.ts (${rows.length} hours)`);
